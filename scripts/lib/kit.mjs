// kit.json: the page's design choices. applyKit() turns them into files.

import fs from "node:fs"
import path from "node:path"
import { ASSETS, dataDir, fail, readJson, versions, writeIfChanged, writeJson } from "./common.mjs"

export const STYLES = ["vega", "nova", "maia", "lyra", "mira", "luma", "sera", "rhea"]
export const ICONS = ["lucide", "tabler", "phosphor", "hugeicons", "remixicon"]
export const ROUTES = ["react", "html"]
export const HTML_UI = ["basecoat", "daisyui", "none"]
export const SCHEMES = ["system", "light", "dark"]

const shadcn = path.join(ASSETS, "react", "shadcn")
export const manifest = () => readJson(path.join(shadcn, "manifest.json"))
const themes = () => readJson(path.join(shadcn, "themes.json"))

export const BASE_DEPS = {
  react: {
    dependencies: ["react", "react-dom", "cn", "class-variance-authority", "radix-ui"],
    devDependencies: ["vite", "@vitejs/plugin-react", "vite-plugin-singlefile", "tailwindcss", "@tailwindcss/vite", "tw-animate-css", "@types/react", "@types/react-dom"],
  },
  html: {
    dependencies: [],
    devDependencies: ["vite", "vite-plugin-singlefile", "tailwindcss", "@tailwindcss/vite"],
  },
}

export function defaultKit(route) {
  return route === "html"
    ? { route, ui: "basecoat", style: "vega", theme: "neutral", accent: null, colorScheme: "system" }
    : { route, style: "vega", theme: "neutral", accent: null, icons: "lucide", colorScheme: "system" }
}

export function validateKit(kit) {
  const bad = (k, list) => fail(`kit.json "${k}" is "${kit[k]}"; use one of: ${list.join(", ")}`)
  if (!ROUTES.includes(kit.route)) bad("route", ROUTES)
  if (kit.style && !STYLES.includes(kit.style)) bad("style", STYLES)
  if (kit.route === "react" && !ICONS.includes(kit.icons)) bad("icons", ICONS)
  if (kit.route === "html" && !HTML_UI.includes(kit.ui)) bad("ui", HTML_UI)
  if (kit.colorScheme && !SCHEMES.includes(kit.colorScheme)) bad("colorScheme", SCHEMES)
  if (kit.accent && !themes().accent[kit.accent]) bad("accent", Object.keys(themes().accent))
}

// A theme is a built-in base color, a .css file path, or the name of a file in
// <data dir>/themes/ (the user's own themes, shared by every page).
export function resolveTheme(kit, pageDir) {
  const t = kit.theme ?? "neutral"
  if (/[\\/]|\.css$/i.test(t)) {
    const file = path.resolve(pageDir, t)
    if (!fs.existsSync(file)) fail(`theme file not found: ${file}`)
    return { css: fs.readFileSync(file, "utf8"), source: file }
  }
  const user = path.join(dataDir(), "themes", `${t}.css`)
  if (fs.existsSync(user)) return { css: fs.readFileSync(user, "utf8"), source: user }
  const all = themes()
  if (!all.base[t]) {
    fail(`unknown theme "${t}". Built-in: ${Object.keys(all.base).join(", ")}; or a .css path; or put ${t}.css in ${path.join(dataDir(), "themes")}`)
  }
  return { css: tokensCss(t, kit.accent), source: `built-in:${t}${kit.accent ? `+${kit.accent}` : ""}` }
}

export function tokensCss(base, accent) {
  const all = themes()
  const light = { ...all.base[base].light, ...(accent ? all.accent[accent].light : {}) }
  const dark = { ...all.base[base].dark, ...(accent ? all.accent[accent].dark : {}) }
  const block = (sel, vars) => `${sel} {\n${Object.entries(vars).map(([k, v]) => `  --${k}: ${v};`).join("\n")}\n}\n`
  return `/* Generated by ohmypage: theme "${base}"${accent ? `, accent "${accent}"` : ""}. Change kit.json and run scripts/apply.mjs. */\n${block(":root", light)}\n${block(".dark", dark)}`
}

function setHtmlAttrs(file, attrs) {
  let html = fs.readFileSync(file, "utf8")
  const m = html.match(/<html\b[^>]*>/i)
  if (!m) return
  let tag = m[0]
  for (const [name, value] of Object.entries(attrs)) {
    if (name === "class") {
      const cls = (tag.match(/\bclass="([^"]*)"/)?.[1] ?? "").split(/\s+/).filter((c) => c && !c.startsWith("style-"))
      if (value) cls.unshift(value)
      tag = /\bclass="/.test(tag) ? tag.replace(/\bclass="[^"]*"/, `class="${cls.join(" ")}"`) : tag.replace(/>$/, ` class="${cls.join(" ")}">`)
      continue
    }
    const re = new RegExp(`\\s${name}="[^"]*"`)
    if (value == null) tag = tag.replace(re, "")
    else tag = re.test(tag) ? tag.replace(re, ` ${name}="${value}"`) : tag.replace(/>$/, ` ${name}="${value}">`)
  }
  writeIfChanged(file, html.replace(m[0], tag))
}

// Bring package.json in line with kit.json. Returns true if dependencies changed.
export function syncDeps(pageDir, kit, extra = []) {
  const file = path.join(pageDir, "package.json")
  const pkg = readJson(file)
  const v = versions()
  const before = JSON.stringify([pkg.dependencies, pkg.devDependencies])
  pkg.dependencies ??= {}
  pkg.devDependencies ??= {}
  const base = BASE_DEPS[kit.route]
  for (const d of base.dependencies) pkg.dependencies[d] ??= v[d]
  for (const d of base.devDependencies) pkg.devDependencies[d] ??= v[d]
  if (kit.route === "react") {
    const iconDeps = manifest().iconDeps
    for (const [lib, deps] of Object.entries(iconDeps)) {
      for (const d of deps) {
        if (lib === kit.icons) pkg.dependencies[d] ??= v[d]
        else delete pkg.dependencies[d]
      }
    }
  } else {
    for (const ui of ["basecoat-css", "daisyui"]) delete pkg.devDependencies[ui]
    if (kit.ui === "basecoat") pkg.devDependencies["basecoat-css"] = v["basecoat-css"]
    if (kit.ui === "daisyui") pkg.devDependencies.daisyui = v.daisyui
  }
  for (const d of extra) pkg.dependencies[d] ??= v[d] ?? "latest"
  const sort = (o) => Object.fromEntries(Object.entries(o).sort(([a], [b]) => a.localeCompare(b)))
  pkg.dependencies = sort(pkg.dependencies)
  pkg.devDependencies = sort(pkg.devDependencies)
  writeJson(file, pkg)
  return before !== JSON.stringify([pkg.dependencies, pkg.devDependencies])
}

// The style sheets cover every component (~250 KB of CSS). Keep only the
// sections for components this page has, so pages stay small.
const SECTION_ALIAS = { toast: "sonner" }
const MENU_USERS = ["combobox", "select", "menubar", "dropdown-menu", "context-menu"]
export function styleCss(style, pageDir) {
  const full = fs.readFileSync(path.join(shadcn, "styles", `${style}.css`), "utf8")
  const uiDir = path.join(pageDir, "src", "components", "ui")
  const have = new Set(fs.existsSync(uiDir) ? fs.readdirSync(uiDir).map((f) => f.replace(/\.tsx$/, "")) : [])
  const parts = full.split(/(?=^  \/\* MARK: )/m)
  const kept = parts.filter((part, i) => {
    if (i === 0) return true
    const name = part.match(/MARK: (.+?) \*\//)[1]
    const slug = name.toLowerCase().replace(/\s+/g, "-")
    if (slug === "react-aria") return false
    if (slug === "menu-translucent") return MENU_USERS.some((c) => have.has(c))
    if (!(slug in SECTION_ALIAS) && !manifest().components[slug]) return true
    return have.has(SECTION_ALIAS[slug] ?? slug)
  })
  let css = kept.join("")
  if (!css.trimEnd().endsWith("}")) css = css.trimEnd() + "\n}\n"
  // The last kept section may have lost the closing brace of the wrapper.
  const open = (css.match(/{/g) || []).length
  const close = (css.match(/}/g) || []).length
  if (open > close) css = css.trimEnd() + "\n}\n"
  // Unwrap `.style-x { }` into the components layer: the wrapper class would raise
  // specificity above Tailwind utilities, so className overrides like text-right would lose.
  css = css.replace(new RegExp(`^\\.style-${style} \\{`, "m"), "@layer components {")
  return `/* Generated by ohmypage: shadcn style "${style}", sections for this page's components only. */\n${css}`
}

const HTML_BASE_TOKENS = `@custom-variant dark (&:is(.dark *));\n`

export function applyKit(pageDir) {
  const kit = readJson(path.join(pageDir, "kit.json"))
  validateKit(kit)
  const style = kit.style ?? "vega"
  const theme = resolveTheme(kit, pageDir)
  const src = path.join(pageDir, "src")
  const scheme = kit.colorScheme ?? "system"

  if (kit.route === "react") {
    writeIfChanged(path.join(src, "styles", "theme.css"), theme.css)
    writeIfChanged(path.join(src, "styles", "style.css"), styleCss(style, pageDir))
    writeIfChanged(path.join(src, "styles", "shadcn-base.css"), fs.readFileSync(path.join(shadcn, "base.css"), "utf8"))
    writeIfChanged(path.join(src, "components", "ui", "icon-placeholder.tsx"), fs.readFileSync(path.join(shadcn, "icons", `${kit.icons}.tsx`), "utf8"))
    setHtmlAttrs(path.join(pageDir, "index.html"), { class: `style-${style}`, "data-color-scheme": scheme })
  } else {
    const head = `/* Generated by ohmypage from kit.json. Put page styles in src/page.css. */\n@import "tailwindcss" source(none);\n`
    const sources = `@source "../index.html";\n@source "./";\n`
    let css
    if (kit.ui === "basecoat") {
      css = `${head}@import "basecoat-css/${style}";\n@import "./styles/theme.css";\n@import "./page.css";\n${sources}`
    } else if (kit.ui === "daisyui") {
      const [l, d] = kit.daisyThemes ?? ["light", "dark"]
      css = `${head}@import "./page.css";\n${sources}@plugin "daisyui" {\n  themes: ${l} --default, ${d} --prefersdark;\n}\n`
    } else {
      const react = fs.readFileSync(path.join(ASSETS, "react", "template", "src", "index.css"), "utf8")
      const themeBlock = react.slice(react.indexOf("@theme inline"), react.indexOf("/* ---- page styles"))
      css = `${head}@import "./styles/theme.css";\n@import "./page.css";\n${sources}\n${HTML_BASE_TOKENS}\n${themeBlock}`
    }
    // Every @import stays above the other rules, as CSS requires.
    writeIfChanged(path.join(src, "main.css"), css)
    if (!fs.existsSync(path.join(src, "page.css"))) writeIfChanged(path.join(src, "page.css"), "/* Page styles. Tailwind utilities work in index.html directly. */\n")
    if (kit.ui !== "daisyui") writeIfChanged(path.join(src, "styles", "theme.css"), theme.css)
    writeIfChanged(path.join(src, "ui.js"), kit.ui === "basecoat" ? `// Managed by ohmypage: Basecoat's behavior for dropdowns, tabs, dialogs, etc.\nimport "basecoat-css/all"\n` : `// Managed by ohmypage. Nothing to load for ui "${kit.ui}".\n`)
    const [l, d] = kit.daisyThemes ?? ["light", "dark"]
    setHtmlAttrs(path.join(pageDir, "index.html"), {
      "data-color-scheme": scheme,
      "data-theme-light": kit.ui === "daisyui" ? l : null,
      "data-theme-dark": kit.ui === "daisyui" ? d : null,
    })
  }
  const depsChanged = syncDeps(pageDir, kit)
  return { kit, depsChanged, themeSource: theme.source }
}
